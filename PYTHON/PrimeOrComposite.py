a = int(input("enter the number : "))
j = 2

while (j<a) :
    if a%j==0 :
      def composite(a):
          return ("%s is a composite number"%(a))  
      print(composite(a))
      break
    else :
       j = j + 1 
    if j==(a-1):
        def prime(a):
            return ("%s is a prime number"%(a))
        print(prime(a))
        break
       
       
    
         
